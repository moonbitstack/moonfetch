"""Generate src/psl_data.mbt from the Public Suffix List.

The list is pinned by the VERSION line written into the generated file; rerun this
script against a newer list and commit both. Only the ICANN section is used: a
cookie's Domain is compared against the suffixes a registry hands out, not the
private ones a hosting service does.

    python scripts/gen_public_suffix.py [path-to-public_suffix_list.dat]
"""

import sys
import urllib.request

URL = "https://publicsuffix.org/list/public_suffix_list.dat"
OUT = "src/psl_data.mbt"


def labels(text):
    """A rule in ASCII labels, or None when a label cannot be converted."""
    out = []
    for part in text.split("."):
        if not part:
            return None
        if all(ord(c) < 128 for c in part):
            out.append(part.lower())
        else:
            try:
                out.append(part.encode("idna").decode("ascii").lower())
            except UnicodeError:
                return None
    return ".".join(out)


def main():
    if len(sys.argv) > 1:
        with open(sys.argv[1], encoding="utf-8") as handle:
            text = handle.read()
    else:
        with urllib.request.urlopen(URL, timeout=60) as response:
            text = response.read().decode("utf-8")

    version = "unknown"
    exact, wild, except_ = [], [], []
    icann = False
    for line in text.splitlines():
        line = line.strip()
        if line.startswith("// VERSION:"):
            version = line.split(":", 1)[1].strip()
        if line == "// ===BEGIN ICANN DOMAINS===":
            icann = True
            continue
        if line == "// ===END ICANN DOMAINS===":
            icann = False
            continue
        if not icann or not line or line.startswith("//"):
            continue
        rule = line.split()[0]
        if rule.startswith("!"):
            name = labels(rule[1:])
            if name:
                except_.append(name)
        elif rule.startswith("*."):
            name = labels(rule[2:])
            if name:
                wild.append(name)
        else:
            name = labels(rule)
            if name:
                exact.append(name)

    def block(name, rules):
        rules = sorted(set(rules))
        body = ",\n".join('  "%s"' % r for r in rules)
        return "///|\nlet %s : Array[String] = [\n%s,\n]\n" % (name, body)

    header = (
        "// Generated by scripts/gen_public_suffix.py from the Public Suffix List,\n"
        "// version %s. Rerun the script rather than editing; the data is ICANN's.\n\n"
        % version
    )
    with open(OUT, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(header)
        handle.write(block("exact_suffixes", exact))
        handle.write("\n")
        handle.write(block("wild_suffixes", wild))
        handle.write("\n")
        handle.write(block("exception_suffixes", except_))
    print("wrote %s: %d exact, %d wildcard, %d exception"
          % (OUT, len(set(exact)), len(set(wild)), len(set(except_))))


if __name__ == "__main__":
    main()
