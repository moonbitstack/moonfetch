"""Write src/fixtures_test.mbt: a root, a localhost server certificate under it, its key, and a
second root that trusts nothing here.

Issued by Python's `cryptography` (OpenSSL); rerun after changing a fixture.
"""

import datetime as dt
import ipaddress
import pathlib

from cryptography import x509
from cryptography.hazmat.primitives import hashes, serialization
from cryptography.hazmat.primitives.asymmetric import ec
from cryptography.x509.oid import ExtendedKeyUsageOID, NameOID

OUT = pathlib.Path(__file__).resolve().parent.parent / "src" / "fixtures_test.mbt"
START = dt.datetime(2020, 1, 1, tzinfo=dt.timezone.utc)
END = dt.datetime(2040, 1, 1, tzinfo=dt.timezone.utc)


def name(cn):
    return x509.Name([x509.NameAttribute(NameOID.COMMON_NAME, cn)])


def root(cn):
    key = ec.generate_private_key(ec.SECP256R1())
    cert = (x509.CertificateBuilder()
            .subject_name(name(cn)).issuer_name(name(cn))
            .public_key(key.public_key())
            .serial_number(x509.random_serial_number())
            .not_valid_before(START).not_valid_after(END)
            .add_extension(x509.BasicConstraints(ca=True, path_length=None), critical=True)
            .sign(key, hashes.SHA256()))
    return cert, key


def leaf(issuer):
    issuer_cert, issuer_key = issuer
    key = ec.generate_private_key(ec.SECP256R1())
    san = x509.SubjectAlternativeName([
        x509.DNSName("localhost"), x509.IPAddress(ipaddress.ip_address("127.0.0.1"))])
    cert = (x509.CertificateBuilder()
            .subject_name(name("localhost")).issuer_name(issuer_cert.subject)
            .public_key(key.public_key())
            .serial_number(x509.random_serial_number())
            .not_valid_before(START).not_valid_after(END)
            .add_extension(san, critical=False)
            .add_extension(x509.ExtendedKeyUsage([ExtendedKeyUsageOID.SERVER_AUTH]), critical=False)
            .sign(issuer_key, hashes.SHA256()))
    return cert, key


def pem(cert):
    return cert.public_bytes(serialization.Encoding.PEM).decode().strip()


def main():
    ca = root("moonfetch test root")
    cert, key = leaf(ca)
    values = {
        "root": pem(ca[0]),
        "other_root": pem(root("unrelated root")[0]),
        "cert": pem(cert),
        "key": key.private_bytes(serialization.Encoding.PEM, serialization.PrivateFormat.PKCS8,
                                 serialization.NoEncryption()).decode().strip(),
    }
    out = ["// Generated by scripts/gen_certs.py; rerun it rather than editing.", ""]
    for k, v in values.items():
        out.append("///|")
        out.append(f"let {k} : String =")
        out.extend("  #|" + line for line in v.split("\n"))
        out.append("")
    OUT.write_text("\n".join(out), encoding="utf-8", newline="\n")
    print(f"wrote {len(values)} values to {OUT}")


if __name__ == "__main__":
    main()
